import { describe, expect, it } from 'vitest';
import { toParagraphs } from '../src/lib/paragraphs';

describe('PDF 줄 → 문단', () => {
  it('끊긴 문장은 잇고, 절 제목·표 머리·날짜로 끝나는 표 행은 따로 둔다', () => {
    const lines = ['□ 향후 조치', '과제 담당 기한', '개정 조문 대비표 작성 이서연 2026. 11. 12.', '참가기관 의견 반영안 정리 최민서 2026. 11. 19.', '□ 유의사항', '○ 다만, 참가기관 의견 반영안은 업무협의회', '결과와 맞춰야 함.'];
    expect(toParagraphs(lines)).toEqual(['□ 향후 조치', '과제 담당 기한', '개정 조문 대비표 작성 이서연 2026. 11. 12.', '참가기관 의견 반영안 정리 최민서 2026. 11. 19.', '□ 유의사항', '○ 다만, 참가기관 의견 반영안은 업무협의회 결과와 맞춰야 함.']);
  });
  it('업무잇다 시연 보고자료 모양은 그대로(글머리표마다 한 문단)', () => {
    const lines = ['비대면 출금동의 추진 현황 보고', '작성일: 2026. 9. 15.(화) · 디지털신원팀', '□ 보고 목적', '○ 비대면 출금동의 방식 확대 추진 현황을 공유하고 향후 일정을 정하기 위함.'];
    expect(toParagraphs(lines)).toEqual(lines);
  });
});
