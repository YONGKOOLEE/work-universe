/** (b) 제안 단계에 남은 잘못(모두 체크 해제 상태): 사번 불일치·같은 이름 다른 사번·사람을 업무로(hold), 뒤집는 문장이 따로 있는 글(ctxVeto) */
const KNOWN_PROPOSAL_WRONG = new Set(["T30", "T31", "T75", "T76", "T77", "T104"]);

const view = viewOf('U-A1');

function judge(text) {
  const p = extractFromText(text, view);
  const sel = defaultSelection(p, 'existing-only');
  const lab = (key) => { const n = p.nodes.find((x) => x.key === key); return n.match_label || n.label; };
  const fmt = (e) => `${e.type} ${lab(e.from)}>${lab(e.to)}`;
  return { p, checked: p.edges.filter((e) => sel.edges[e.key].include && sel.nodes[e.from].include && sel.nodes[e.to].include).map(fmt), all: p.edges.map(fmt) };
}

for (const [k, id, text, exp, memo] of CASES) {
  test(`R18 세 번째 줄글 ${id} [${k}] ${text} (${memo})`, () => {
    const { p, checked, all } = judge(text);
    assert.deepEqual(checked.filter((x) => !exp.includes(x)), [], '처음 체크된 채 잘못 읽음');
    const wrong = all.filter((x) => !exp.includes(x));
    if (wrong.length) assert.ok(KNOWN_PROPOSAL_WRONG.has(id), `새로 생긴 제안 단계 잘못: ${JSON.stringify(wrong)}`);
    const used = new Set([...p.nodes, ...p.edges].map((x) => x.quote));
    for (const s of splitSentences(text)) assert.ok(used.has(s) || p.unread.includes(s), `말없이 놓침: ${s}`);
  });
}

test('R18 세 번째 줄글: 사실 문장을 읽는 비율이 70% 이상이고, 제안 단계 잘못은 알려진 목록보다 늘지 않으며, 처음 체크된 채 잘못은 0건', () => {
  const facts = CASES.filter(([k]) => k === 'F');
  let read = 0;
  let wrongChecked = 0;
  let wrongProposal = 0;
  for (const [k, , text, exp] of CASES) {
    const { checked, all } = judge(text);
    wrongChecked += checked.filter((x) => !exp.includes(x)).length;
    if (all.some((x) => !exp.includes(x))) wrongProposal += 1;
    if (k === 'F' && exp.every((x) => all.includes(x)) && !all.some((x) => !exp.includes(x))) read += 1;
  }
  assert.equal(wrongChecked, 0);
  assert.ok(wrongProposal <= KNOWN_PROPOSAL_WRONG.size, `제안 단계 잘못 ${wrongProposal}`);
  assert.ok(read / facts.length >= 0.7, `사실 문장 읽음 ${read}/${facts.length}`);
});
