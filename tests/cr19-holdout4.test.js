const view = viewOf('U-A1');

function judge(text, mode) {
  const p = extractFromText(text, view);
  const sel = defaultSelection(p, mode);
  const lab = new Map(p.nodes.map((n) => [n.key, n.match_label || n.label]));
  const edges = p.edges.map((e) => ({ s: `${lab.get(e.from)}>${e.type}>${lab.get(e.to)}`, exists: !!e.exists, checked: !!sel.edges[e.key].include && !!sel.nodes[e.from].include && !!sel.nodes[e.to].include }));
  return { p, sel, edges };
}

for (const [id, g, text, want, allow, fact] of CASES) {
  test(`R19 네 번째 시험 ${id} [${g}] ${JSON.stringify(text)}`, () => {
    const ok = new Set([...want, ...allow]);
    const { p, sel, edges } = judge(text, 'existing-only');
    // (a) 처음 체크된 채 잘못 = 0
    assert.deepEqual(edges.filter((e) => e.checked && !ok.has(e.s) && !e.exists).map((e) => e.s), [], "'existing-only'에서 처음 체크된 채 잘못 읽음");
    // 기본 모드('none')에서는 아무것도 처음 체크하지 않는다
    const none = judge(text, undefined);
    assert.ok(none.edges.every((e) => !e.checked) && Object.values(none.sel.nodes).every((n) => !n.include), '기본(none): 처음 체크 0');
    // 사실 문장은 연결을 읽는다
    if (fact) assert.deepEqual(want.filter((w) => !edges.some((e) => e.s === w)), [], '사실 연결을 읽어야 한다');
    // 말없이 놓침 = 0
    const used = new Set([...p.nodes, ...p.edges].map((x) => x.quote));
    for (const s of splitSentences(text)) assert.ok(used.has(s) || p.unread.includes(s), `말없이 놓침: ${s}`);
  });
}

test('R19 네 번째 시험 요약: 사실 연결 읽음 46/46, 처음 체크된 채 잘못 0(existing-only)', () => {
  let got = 0;
  let wantN = 0;
  let wrong = 0;
  for (const [, , text, want, allow, fact] of CASES) {
    const ok = new Set([...want, ...allow]);
    const { edges } = judge(text, 'existing-only');
    wrong += edges.filter((e) => e.checked && !ok.has(e.s) && !e.exists).length;
    if (fact) {
      wantN += want.length;
      got += want.filter((w) => edges.some((e) => e.s === w)).length;
    }
  }
  assert.equal(CASES.length, 140);
  assert.equal(wrong, 0);
  assert.equal(`${got}/${wantN}`, '46/46');
});
